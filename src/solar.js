/* ---------- V · Солнечная система ----------------------------------------
   Станция «Солнце» получает два слоя: 0 — вся система целиком, 1 — само Солнце.
   Приближение и к Солнцу, и к отдельной планете сделано ОДНИМ механизмом: группа
   системы масштабируется относительно точки фокуса, а камера наводится на эту же
   точку. Точка остаётся неподвижной в кадре, всё остальное разлетается мимо —
   тот же принцип, что у зума «Вселенная → Галактика», и по той же причине: поток
   на экране должен быть радиальным из одной точки, иначе это читается не как
   полёт, а как «объект растёт».                                             */

