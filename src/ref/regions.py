import cv2
def refine(m, img, grow=14, shrink=9, cut=True):
    # GrabCut внутри полосы вокруг грубого контура — граница прилипает к реальному краю
    if not cut: return m
    k=lambda r: cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(2*r+1,2*r+1))
    mu=m.astype(np.uint8)
    dil=cv2.dilate(mu,k(grow)); ero=cv2.erode(mu,k(shrink))
    ys,xs=np.nonzero(dil)
    if len(xs)==0: return m
    x0,x1=max(0,xs.min()-20),min(N,xs.max()+21); y0,y1=max(0,ys.min()-20),min(N,ys.max()+21)
    gm=np.full((y1-y0,x1-x0),cv2.GC_BGD,np.uint8)
    gm[dil[y0:y1,x0:x1]>0]=cv2.GC_PR_BGD
    gm[mu[y0:y1,x0:x1]>0]=cv2.GC_PR_FGD
    gm[ero[y0:y1,x0:x1]>0]=cv2.GC_FGD
    if (gm==cv2.GC_FGD).sum()<30: return m
    rgb=img[y0:y1,x0:x1,:3].astype(np.float32)*(img[y0:y1,x0:x1,3:4]/255.)
    bgd=np.zeros((1,65),np.float64); fgd=np.zeros((1,65),np.float64)
    try: cv2.grabCut(np.ascontiguousarray(rgb.astype(np.uint8)[...,::-1]),gm,None,bgd,fgd,5,cv2.GC_INIT_WITH_MASK)
    except Exception as e: print('gc fail',e); return m
    fg=np.isin(gm,[cv2.GC_FGD,cv2.GC_PR_FGD]).astype(np.uint8)
    fg=cv2.morphologyEx(fg,cv2.MORPH_OPEN,k(4)); fg=cv2.morphologyEx(fg,cv2.MORPH_CLOSE,k(6))
    # оставить связные куски, касающиеся исходной сердцевины
    n,lab=cv2.connectedComponents(fg)
    keep=np.zeros_like(fg)
    core=ero[y0:y1,x0:x1]>0
    for i in range(1,n):
        if (core&(lab==i)).any(): keep[lab==i]=1
    fg=cv2.GaussianBlur(keep.astype(np.float32),(0,0),2.5)>.5
    out=np.zeros((N,N),bool); out[y0:y1,x0:x1]=fg
    return out
def poly_mask(poly):
    im=Image.new('L',(N,N),0); ImageDraw.Draw(im).polygon(poly,fill=255); return np.array(im)>0
yy,xx=np.mgrid[0:N,0:N].astype(np.float32)
def cap(p0,p1,r):
    p0=np.array(p0,np.float32); p1=np.array(p1,np.float32); d=p1-p0; L2=(d**2).sum()
    t=np.clip(((xx-p0[0])*d[0]+(yy-p0[1])*d[1])/L2,0,1)
    dist=np.hypot(xx-(p0[0]+t*d[0]), yy-(p0[1]+t*d[1]))
    return dist<r, t
def build(kind, defs):
    img=np.array(Image.open(f'ref/{kind}_al.png'))
    a=img[...,3]/255.
    softm={}
    idm=np.zeros((N,N),np.uint8); G=np.zeros((N,N),np.float32); B=np.zeros((N,N),np.float32)
    meta=[]; nid=0; keymap={}
    for d in defs:
        key=d[0]
        if kind=='org': name,desc,prac,fx,shapes=d[1],d[2],d[3],d[4],d[5]; typ=None
        elif kind=='mus': name,desc,prac,shapes=d[1],d[2],d[3],d[4]; fx=0; typ=None
        else: name,desc,prac,typ,shapes=d[1],d[2],d[3],d[4],d[5]; fx=0
        if key in keymap: rid=keymap[key]
        elif name is None: rid=keymap['ribs']
        else:
            nid+=1; rid=nid; keymap[key]=rid
            meta.append(dict(id=rid,key=key,name=name,desc=desc,note=prac,fx=fx,type=typ))
        thr = .45 if kind=='bone' else (.12 if key=='vess' else .3)
        for s in shapes:
            if kind=='bone':
                if s[0]=='p': m=poly_mask(s[1]); t=None
                else: m,t=cap(s[1],s[2],s[3])
            else:
                m=poly_mask(s); t=None
                m=refine(m, img, cut=(key not in ('vess','gall','panc','trach')))
            m=m&(a>thr)
            idm[m]=rid
            softm.setdefault(rid,[]).append(m.copy())
            ys_,xs_=np.nonzero(m)
            if len(xs_) and name is not None:
                md=[x for x in meta if x['id']==rid][0]
                md.setdefault('parts',[]).append([round(float(xs_.mean()/N),4), round(float(ys_.mean()/N),4), round(float(np.sqrt(len(xs_)/np.pi)/N),4)])
            if kind=='bone':
                if typ=='long': sp=1-np.clip((np.minimum(t,1-t)-.08)/.1,0,1); B[m]=sp[m]
                elif typ=='spongy': B[m]=1.0
                else: B[m]=0.85
    if kind=='bone':
        solid=a>.45
        dist=ndi.distance_transform_edt(solid)
        mx=ndi.maximum_filter(dist,size=31)
        G=np.where(solid, np.clip(dist/np.maximum(mx,1.5),0,1),0)
    # центры и радиусы
    for m in meta:
        ys,xs=np.nonzero(idm==m['id'])
        if len(xs)==0: print('EMPTY',m['key']); continue
        m['c']=[round(float(xs.mean()/N),4), round(float(ys.mean()/N),4)]
        m['n']=int(len(xs))
    # мягкие маски: 4x4 плитки по 256 px, в каждой — размытая маска области (с учётом перекрытий)
    atlas=np.zeros((1024,1024),np.float32)
    for rid in range(1,nid+1):
        own=(idm==rid).astype(np.float32)
        sm=cv2.GaussianBlur(own,(0,0),7.0)
        sm=np.clip(sm*1.7,0,1)
        sm=cv2.resize(sm,(256,256),interpolation=cv2.INTER_AREA)
        r,c=divmod(rid-1,4)
        atlas[r*256:(r+1)*256,c*256:(c+1)*256]=sm
    Image.fromarray((atlas*255).astype(np.uint8),'L').save(f'ref/out/{kind}_s.png',optimize=True)
    out=np.stack([idm.astype(np.float32)*10, G*255, B*255],-1).clip(0,255).astype(np.uint8)
    Image.fromarray(out,'RGB').save(f'ref/out/{kind}_d.png', optimize=True)
    Image.open(f'ref/{kind}_al.png').save(f'ref/out/{kind}.webp', quality=86, method=6)
    # отладка
    rng=np.random.RandomState(3); pal=rng.randint(60,255,(40,3))
    base=Image.new('RGBA',(N,N),(8,10,20,255)); base.alpha_composite(Image.fromarray(img,'RGBA'))
    b=np.array(base).astype(np.float32)
    ov=pal[idm]; msk=(idm>0)[...,None]
    b[...,:3]=np.where(msk, b[...,:3]*.45+ov*.55, b[...,:3])
    dbg=Image.fromarray(b.astype(np.uint8),'RGBA').convert('RGB'); dr=ImageDraw.Draw(dbg)
    for m in meta:
        if 'c' in m: dr.text((m['c'][0]*N-15,m['c'][1]*N),m['key'],fill=(255,255,255))
    dbg.save(f'ref/{kind}_regions.png')
    if kind=='bone':
        Image.fromarray((np.stack([G*255,B*255,np.zeros_like(G)],-1)).astype(np.uint8)).save('ref/bone_struct.png')
    return meta
