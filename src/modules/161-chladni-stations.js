// ===== Фигуры Хладни: слой 1 станции II «Первоимпульс» =====
// Квадратная пластина, на ней песок. Колебание пластины — сумма собственных мод; каждая мода откликается
// по резонансной кривой на частоту возбуждения. Песок подбрасывается там, где пластина движется, и
// скатывается туда, где она стоит, — на узловые линии. Это не нарисованный узор, а маленькая симуляция:
// песчинки сами ползут по градиенту u² и дрожат пропорционально |u|. Между резонансами амплитуда мала —
// песок почти не движется и узора не находит, как и на настоящей пластине.
// Моды — классическое приближение для свободной квадратной пластины:
//   φ(n,m) = cos(nπx)·cos(mπy) ∓ cos(mπx)·cos(nπy),  x, y ∈ [0, 1],  частота ∝ n² + m²
// (точные частоты свободной пластины другие — в тексте слоя это сказано)
// у части мод знак «+» (cos·cos + cos·cos): узор без диагонали — кольца, кресты, звёзды
const CY_MODES = [[1,2,-1],[1,3,1],[2,3,-1],[1,4,-1],[2,4,1],[3,4,-1],[2,5,-1],[3,5,1],[1,6,-1],[4,5,-1],[3,7,1],[5,6,-1]]
  .map(([n, m, s]) => ({ n, m, s, f: 40*(n*n + m*m) }));
const CY_FMIN = 150, CY_FMAX = 2600;
let CYM = null;      // состояние опыта — панель управляет им отсюда
function buildChladni(g){
  const S = 3.7;                                        // полусторона пластины в единицах сцены
  const plate = new THREE.Group(); plate.visible = false; g.add(plate);
  const qTilt = new THREE.Quaternion().setFromEuler(new THREE.Euler(-.42, 0, 0)), qZ = new THREE.Quaternion(), AZ = new THREE.Vector3(0, 0, 1);
  // рамка пластины и слабая подсветка её поверхности
  const frame = new THREE.LineLoop(new THREE.BufferGeometry().setFromPoints([[-1,-1],[1,-1],[1,1],[-1,1]].map(([x, y]) => new THREE.Vector3(x*S, y*S, 0))), lineMat(0xD6AC5E, .7));
  frame.userData.self = true; plate.add(frame);
  const stem = glow(0xD6AC5E, .5, .6); stem.userData.self = true; plate.add(stem);    // точка крепления в центре
  // поверхность: сетка точек показывает саму вибрацию — светится там, где пластина колеблется
  const GR = Math.round(70*Math.sqrt(Q));
  const surf = pts(GR*GR, (i, o) => { const a = i % GR, b = Math.floor(i/GR);
      o.p = [((a + .5)/GR*2 - 1)*S, ((b + .5)/GR*2 - 1)*S, -.02]; o.c = C(0x8f7bff); o.s = .9; },
    `float k = aRnd.x;                                      // |u| в этой точке, пишется из JS
     a = (0.03 + 0.30*k)*uSharp*(0.7 + 0.3*sin(uTime*30.0 + aSeed*20.0));
     col = mix(vec3(0.35,0.28,0.85), vec3(0.75,0.62,1.0), k);`);
  surf.geometry.attributes.aRnd.setUsage(THREE.DynamicDrawUsage);
  plate.add(surf);
  // песок: положение — из JS; uProg — растворение в общую сферу на стыке со «Вселенной» (та же формула,
  // что у узла станции II и у паутины станции III, иначе облака на стыке не совпадут)
  const NS = Math.round(7000*Q);
  const X = new Float32Array(NS), Y = new Float32Array(NS);
  for (let i = 0; i < NS; i++){ X[i] = Math.random(); Y[i] = Math.random(); }
  const sand = pts(NS, (i, o) => { o.p = [0, 0, 0]; o.c = mixc(C(0xffe2a8), C(0xfff6e6), Math.random()); o.s = .55 + Math.random()*.5; },
    `vec3 rdir = normalize(vec3(fract(aSeed*13.1), fract(aSeed*37.7), fract(aSeed*71.3)) - 0.5 + 0.0001);
     vec3 dirv = normalize(mix(normalize(position + vec3(0.0001)), rdir, 0.45));
     p = mix(position, dirv*(3.0 + fract(aSeed*7.3)*1.5), uProg);
     col = mix(col, vec3(1.0, 0.96, 0.9), uProg*0.75);
     s *= 1.0 + uProg*1.4;
     a = (0.78 + 0.1*uProg)*uSharp;`);
  sand.geometry.attributes.position.setUsage(THREE.DynamicDrawUsage);
  plate.add(sand);

  const st = { f: CY_MODES[5].f, fT: CY_MODES[5].f, auto: true, lastInput: -1e9, onState: null, tone: null };
  CYM = st;
  // веса мод на текущей частоте (резонанс шириной ~3,5%) и сводка для панели
  const W = new Float32Array(CY_MODES.length);
  function weights(f){ let best = 0, bk = 0;
    for (let k = 0; k < CY_MODES.length; k++){ const x = (f/CY_MODES[k].f - 1)/.035; W[k] = 1/(1 + x*x); if (W[k] > best){ best = W[k]; bk = k; } }
    return { best, bk }; }
  st.state = () => { const w = weights(st.f); return { f: Math.round(st.f), on: w.best > .45, n: CY_MODES[w.bk].n, m: CY_MODES[w.bk].m }; };
  st.set = f => { st.fT = clamp(f, CY_FMIN, CY_FMAX); st.auto = false; st.lastInput = performance.now(); };
  st.scatter = () => { for (let i = 0; i < NS; i++){ X[i] = Math.random(); Y[i] = Math.random(); } };
  // к соседнему резонансу: от текущей цели — ближайшая мода выше (dir > 0) или ниже по частоте
  st.next = dir => { const cand = CY_MODES.filter(M => dir > 0 ? M.f > st.fT*1.01 : M.f < st.fT*.99);
    if (cand.length) st.set(dir > 0 ? cand[0].f : cand[cand.length - 1].f); };
  // поле u и его градиент в точке (x, y) ∈ [0,1]²
  let gx = 0, gy = 0;
  function field(x, y, act){
    let u = 0; gx = 0; gy = 0;
    for (const k of act){ const M = CY_MODES[k], w = W[k], a = M.n*Math.PI, b = M.m*Math.PI;
      const cax = Math.cos(a*x), sax = Math.sin(a*x), cbx = Math.cos(b*x), sbx = Math.sin(b*x);
      const cay = Math.cos(a*y), say = Math.sin(a*y), cby = Math.cos(b*y), sby = Math.sin(b*y);
      const sg = M.s;
      u += w*(cax*cby + sg*cbx*cay);
      gx += w*(-a*sax*cby - sg*b*sbx*cay);
      gy += w*(-b*cax*sby - sg*a*cbx*say); }
    return u;
  }
  const pos = sand.geometry.attributes.position, sr = surf.geometry.attributes.aRnd;
  let stepT = 0;
  return {
    update(t, dt, cym, dis, vis, gz){
      const o = smooth(.35, .9, cym);
      plate.visible = o > .004;
      if (!plate.visible){ if (st.tone) st.tone.gain.gain.value = 0; return; }
      // пластину держим лицом к зрителю: станция II медленно вращается вокруг оси, пластине это ни к чему
      qZ.setFromAxisAngle(AZ, -gz); plate.quaternion.copy(qZ).multiply(qTilt);
      for (const p of [sand, surf]){ const u = p.material.uniforms; u.uSharp.value = o; u.uPush.value = 0; u.uProg.value = dis; }
      frame.material.opacity = .7*o*vis*(1 - dis); stem.material.opacity = .6*o*vis*(1 - dis);
      surf.material.uniforms.uSharp.value = o*(1 - dis);
      // частота: плавно к цели; без касаний — сама переходит к следующему резонансу каждые ~9 с
      if (!st.auto && performance.now() - st.lastInput > 15000) st.auto = true;
      if (st.auto && cym > .97 && dis < .01){ stepT += dt; if (stepT > 9){ stepT = 0; const w = weights(st.fT); st.fT = CY_MODES[(w.bk + 1) % CY_MODES.length].f; } }
      st.f += (st.fT - st.f)*Math.min(1, dt*1.6);
      const w = weights(st.f), act = [];
      for (let k = 0; k < CY_MODES.length; k++) if (W[k] > .02) act.push(k);
      if (st.onState) st.onState(st.state());
      if (st.tone){ st.tone.osc.frequency.value = st.f; st.tone.gain.gain.value = .035*w.best*o*(1 - dis); }
      // песок: шаг по градиенту u² (к узлам) плюс подскок, пропорциональный |u|. Шаг ограничен, чтобы
      // песчинки не перепрыгивали через тонкие линии высоких мод
      if (dis < .02 && cym > .3){
        const h = Math.min(dt, .033), amp = w.best;
        for (let i = 0; i < NS; i++){
          const u = field(X[i], Y[i], act);
          let dx = -u*gx*h*.11, dy = -u*gy*h*.11;
          const L = Math.hypot(dx, dy), lim = .006; if (L > lim){ dx *= lim/L; dy *= lim/L; }
          const j = Math.abs(u)*h*.5*amp;
          X[i] = clamp(X[i] + dx + (Math.random() - .5)*j, 0, 1);
          Y[i] = clamp(Y[i] + dy + (Math.random() - .5)*j, 0, 1);
        }
      }
      for (let i = 0; i < NS; i++){ pos.array[i*3] = (X[i]*2 - 1)*S; pos.array[i*3 + 1] = (Y[i]*2 - 1)*S; pos.array[i*3 + 2] = .02; }
      pos.needsUpdate = true;
      // подсветка поверхности: |u| в узлах сетки
      for (let b = 0, i = 0; b < GR; b++) for (let a = 0; a < GR; a++, i++){
        const u = field((a + .5)/GR, (b + .5)/GR, act); sr.array[i*3] = Math.min(1, Math.abs(u)*.6); }
      sr.needsUpdate = true;
    }
  };
}
