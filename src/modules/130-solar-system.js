/* ---------- V · Солнечная система ----------------------------------------
   Станция «Солнце» получает два слоя: 0 — вся система целиком, 1 — само Солнце.
   Приближение и к Солнцу, и к отдельной планете сделано ОДНИМ механизмом: группа
   системы масштабируется относительно точки фокуса, а камера наводится на эту же
   точку. Точка остаётся неподвижной в кадре, всё остальное разлетается мимо —
   тот же принцип, что у зума «Вселенная → Галактика», и по той же причине: поток
   на экране должен быть радиальным из одной точки, иначе это читается не как
   полёт, а как «объект растёт».                                             */

/* ---------- Погружение в Солнце: от полей до ядра -------------------------
   Устройство то же, что у Земли: сначала «оболочки» вокруг звезды (гелиосфера,
   тяжесть, магнитное поле, корона), затем спуск внутрь — хромосфера, фотосфера,
   конвекция, тахоклин, лучистая зона и ядро. Разница в том, что камера здесь не
   едет по коридору: слой приходит мелким, вырастает и уходит за камеру, а внутри
   него уже виден следующий. Для сферической звезды это честнее коридора и не
   требует отдельной сцены — всё живёт внутри станции V.                     */

